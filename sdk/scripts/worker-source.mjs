// The planning worker (src/worldgen/planWorker.ts) bundled into one script, and the module that carries its text.
import { rolldown } from 'rolldown';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = `${resolve(dirname(fileURLToPath(import.meta.url)), '..')}/`;

/** The path of the generated module, and its source for the script the bundler makes now. */
export async function workerModule() {
  const bundle = await rolldown({ input: `${root}src/worldgen/planWorker.ts`, platform: 'browser', treeshake: { moduleSideEffects: () => true }, logLevel: 'silent' });
  const { output } = await bundle.generate({ format: 'iife', minify: true, codeSplitting: false });
  await bundle.close();
  const text = output.find((c) => c.type === 'chunk').code;
  return {
    path: `${root}src/runtime/planWorkerBundle.generated.ts`,
    bytes: text.length,
    source: `// SPDX-License-Identifier: Apache-2.0
// SPDX-FileCopyrightText: Copyright (c) 2024-present ESEngine Team
// Generated by sdk/scripts/build-worker.mjs from src/worldgen/planWorker.ts: do not edit.
/** The planning worker's script: what a pool of planning workers is started from. */
export const PLAN_WORKER_SOURCE = ${JSON.stringify(text)};
`,
  };
}
