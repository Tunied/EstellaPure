import type { World } from '../../ecs/world';
import type { Entity } from '../../types';
import { UITooltip, type UITooltipData } from '../behavior/tooltip';
import { makeWidgetInteractable } from '../input/interactable';
import { spawnUIEntity, type UINodeInit } from '../core/compose';
import { px } from '../core/dimension';
import { themeColors } from '../theme/tokens';
import { markThemed } from '../theme/theme-style';

/** Attach to an existing control without changing its input configuration. @beta */
export function attachTooltip(world: World, target: Entity, options: Partial<UITooltipData> = {}): void {
    world.insert(target, UITooltip, { ...structuredClone(UITooltip._default), ...options });
}

export interface TooltipOptions {
    world: World;
    parent?: Entity;
    node?: UINodeInit;
    content?: string;
    settings?: Partial<UITooltipData>;
}
export interface TooltipHandle {
    readonly entity: Entity;
    dispose(): void;
}
/** Palette example target. The popup is generated by the behavior at runtime. @beta */
export function createTooltip(opts: TooltipOptions): TooltipHandle {
    const entity = spawnUIEntity({ world: opts.world, parent: opts.parent,
        node: opts.node ?? { width: px(140), height: px(36) }, visual: { color: themeColors().control },
        text: { content: 'Tooltip', color: themeColors().text } });
    markThemed(opts.world, entity, { visual: 'control', text: 'text' });
    makeWidgetInteractable(opts.world, entity);
    attachTooltip(opts.world, entity, { content: opts.content ?? 'More information about this control.', ...opts.settings });
    return { entity, dispose() { if (opts.world.valid(entity)) opts.world.despawn(entity); } };
}
